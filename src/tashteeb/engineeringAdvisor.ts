export interface ProjectContextInfo {
  projectName?: string;
  areaSqm?: number | string;
  budgetEgp?: number | string;
  currentState?: string;
  completedStages?: number;
  activeStageName?: string;
}

export function getEngineeringConsultantResponse(
  query: string,
  context: ProjectContextInfo = {}
): string {
  const q = query.toLowerCase().trim();
  const projectIntro = context.projectName 
    ? `بخصوص مشروعك (${context.projectName} بمساحة ${context.areaSqm || 140}م²): ` 
    : '';

  // 1. استلام المحارة والزوايا والبؤج والأوتار
  if (
    q.includes('محار') || 
    q.includes('بؤج') || 
    q.includes('أوتار') || 
    q.includes('قدة') || 
    q.includes('زوايا') || 
    q.includes('plaster')
  ) {
    return `${projectIntro}أهلاً بك يا هندسة! استلام أعمال المحارة (اللياسة) من أهم المراحل لأنها أساس كل الدهانات والبورسلين التالي. إليك الخطوات الهندسية لاستلام المحارة بدون أي غلطة:

١. الطرطشة المسمارية:
• التأكد من رش الحوائط بالمياه أولاً، ثم طرطشة مسمارية خشنة جداً ومغطية لسطح الطوب بالكامل (عروق الطوب لا تظهر).
• تثبيت شبك فايبر أو سلك بقلاوة معدني عند كل فواصل التقاء الخرسانات مع الطوب وفوق خراطيم الكهرباء لمنع الشروخ والترييح نهائياً.

٢. البؤج والأوتار والزوايا:
• استلام البؤج بميزان المية والقدة الألومنيوم رأسياً وأفقياً.
• الزوايا (بين كل حائطين متجاورين): التأكد من أنها قائمة 90 درجة بالزاوية المعدنية، وتركيب زوايا فلكس (Flex Corner) من الصاج المجلفن في أركان الأعمدة وفتحات الأبواب والشبابيك لحمايتها من الكسر.

٣. استلام المسطحات (الملء والدرع):
• الدرع بقدة ألومنيوم (طول 2.5 أو 3 متر) في كل الاتجاهات: رأسي، أفقي، وقطري. المسموح به فراغ لا يتعدى 2 مم أسفل القدة.
• التأكد من خلو المحارة من التطبيل بالطرق الخفيف بالمفتاح، ومن خلوها من التنميلات أو الحصى البارز.

⚠️ تحذير هندسي هام: لا تبدأ أعمال معجون الدهانات أو الجبسوم بورد إطلاقاً إلا بعد جفاف المحارة تماماً (أسبوعين إلى 20 يوماً على الأقل مع رش المياه يومياً لأول 5 أيام).`;
  }

  // 2. اختبار عزل الحمامات والمطابخ والسباكة
  if (
    q.includes('عزل') || 
    q.includes('غمر') || 
    q.includes('تسريب') || 
    q.includes('waterproof') || 
    q.includes('حمام') || 
    q.includes('حمامات')
  ) {
    return `${projectIntro}العزل المائي للحمام والمطبخ وتراس الشقة هو الخط الدفاعي الأول لحماية خرسانات العمارة ودهانات شقتك وشقة جارك في الدور الأسفل. إليك الأصول الهندسية الصارمة:

١. التجهيز قبل العزل:
• نظافة أرضية الخرسانة تماماً بالمكنسة والسلك من أي مخلفات مباني أو جبس.
• عمل "رقبة زجاجة" (وزرة مائلة دائرية بمونة أسمنتية مقاومة مع مادة أديبوند 65) عند التقاء الأرضية مع الحوائط بارتفاع 20-30 سم.
• دهان وشين عزل كيميائي مرن (مثل سيروبلاست أو كيمابوكسي أو دراي سيل 2K) بزاوية متعامدة بين الوش الأول والثاني.

٢. اختبار الغمر بالمياه (48 ساعة):
• غمر أرضية الحمام بالكامل بمياه بارتفاع 10-15 سم بعد سد كل بالوعات ومواسير الصرف جيداً بـ (طبة كبس).
• تعليم منسوب المياه على الحائط بقلم رصاص.
• متابعة النقص في المنسوب (مع مراعاة التبخر البسيط 2-3 مم).
• النزول لشقة الجار بالأسفل ومعاينة سقف حمامه بدقة تامة؛ يجب ألا تظهر أي نقطة ندى أو ترشيح مياه.

٣. استلام مواسير السباكة وضمانها:
• قبل المحارة وتقفيل الأرضيات، يجب كبس شبكة التغذية (بولي بروبلين) بطلمبة الكبس اليدوية على 10 إلى 15 بار لمدة 24 ساعة بحضور مهندس الشركة المعتمدة (مثل الشريف أو أكواثيرم أو باننجر) واستلام شهادة ضمان معتمدة ومختومة مدى الحياة.`;
  }

  // 3. أسلاك وكابلات السويدي والكهرباء
  if (
    q.includes('سويدي') || 
    q.includes('كهربا') || 
    q.includes('كابل') || 
    q.includes('سلك') || 
    q.includes('برايز') || 
    q.includes('إنارة') || 
    q.includes('لوحة') || 
    q.includes('تكييف') || 
    q.includes('قاطع') || 
    q.includes('electrical')
  ) {
    return `${projectIntro}أعمال تأسيس الكهرباء لا تقبل أي تهاون لأن التأسيس الدفين لا يمكن استبداله بعد السيراميك والمحارة بدون تكسير باهظ التكاليف! إليك الدليل المعتمد:

١. كشف أسلاك السويدي الأصلية المعتمدة:
• الشراء فقط من الموزعين المعتمدين والموثقين (ابتعد تماماً عن الورش والمحلات المجهولة).
• مسح كود الـ QR من على بكرة السلك بواسطة تطبيق "السويدي إليكتريك الأصلي" للتأكد من الرقم التسلسلي.
• النحاس الأصلي لونه أحمر ناصع نقي ومرن، والعزل سميك ومكتوب عليه اسم الشركة والقطاع بوضوح محفور بالليزر.

٢. توزيع القطاعات الهندسية القياسية للأحمال:
• دوائر الإنارة العادية: سلك معتمد 1.5 مم².
• البرايز العادية والأفياش العامة: سلك معتمد 2.5 مم².
• برايز القوى (غسالة ملابس، غسالة أطباق، سخان مياه، ميكروويف، كاتيل): سلك 4 مم².
• خطوط التكييف: تكييف 1.5 - 2.25 حصان يستخدم سلك 4 مم² مع خط مستقل مباشر للوحة. تكييف 3 حصان فأكثر يستخدم سلك 6 مم² مباشر.
• الكابل الرئيسي المغذي للوحة الشقة: لا يقل عن 10 مم² إلى 16 مم² نحاس معتمد حسب مساحة الشقة وأحمال التكييفات.

٣. لوحة القواطع الرئيسية:
• استخدام قواطع معتمدة أصلية (Schneider Electric أو Hager أو ABB).
• إضافة قاطع حماية تفاضلي ضد الصعق الكهربائي والحرائق (Earth Leakage Circuit Breaker - RCCB 30mA).`;
  }

  // 4. البورسلين والأرضيات والرخام والباركيه
  if (
    q.includes('بورسلين') || 
    q.includes('سيراميك') || 
    q.includes('أرضي') || 
    q.includes('رخام') || 
    q.includes('مادة') || 
    q.includes('تطبيل') || 
    q.includes('هالك') || 
    q.includes('كليوباترا') || 
    q.includes('جوهرة') || 
    q.includes('flooring') || 
    q.includes('tile')
  ) {
    return `${projectIntro}في تشطيب الأرضيات والبورسلين، أكثر مشكلة هندسية شائعة هي "تطبيل" وخلع البورسلين بعد فترة. إليك القواعد الذهبية لتفاديها:

١. الفرق الحاسم بين تركيب السيراميك والبورسلين:
• السيراميك: ذو مسامية عالية، ويمكن تركيبه بالطريقة التقليدية (مونة أسمنتية ورملية مبللة بعد غمر البلاطات في الماء).
• البورسلين: ذو مسامية تكاد تكون صفرية (0.05%)، لذلك ممنوع نهائياً تركيبه بمونة أسمنت عادية! يجب تركيبه بـ "مادة لصق بورسلين معتمدة" (مثل سيروبوند أو سيكا أو كيمابوكسي) على فرشة خرسانية/مونة ممسوسة ومستوية تماماً، ودهان ظهر بلاطة البورسلين بالمادة (Butter-coat).

٢. فواصل التمدد والكلبسات (Tile Leveling System):
• استخدام كلبسات تسوية البورسلين لضمان عدم وجود أي "سنّة" (شروق) بين البلاطات واستواء السطح كمرآة واحدة.
• ترك فواصل تمدد بين البلاطات لا تقل عن 2 مم إلى 3 مم وملئها بعراميس معجون روبة مرن عالي الجودة مضاد للبكتيريا، وترك فاصل 8 مم عند التقاء الحوائط يغطيه نعل الوزرة.

٣. حساب الهالك والمشتريات:
• للبلاط العدل: إضافة نسبة هالك 8% إلى 10%.
• للبلاط المائل (زاوية 45 سمبوكسة): إضافة نسبة هالك 12% إلى 15%.
• للمساحات الرئيسية الواسعة (الريسبشن والممرات): احرص دائماً على اختيار فرز أول من مصانع معتمدة (مثل الجوهرة، كليوباترا، رويال، ليسيكو).`;
  }

  // 5. الدهانات والمعجون والجبسوم بورد
  if (
    q.includes('دهان') || 
    q.includes('نقاش') || 
    q.includes('معجون') || 
    q.includes('جبس') || 
    q.includes('سقف') || 
    q.includes('كناوف') || 
    q.includes('جوتن') || 
    q.includes('paint')
  ) {
    return `${projectIntro}الدهانات والأسقف المعلقة هي الواجهة البصرية النهائية التي تبرز كل مجهود التشطيب. إليك بروتوكول التشطيب الفندقي المعتمد:

١. تأسيس الجبسوم بورد (الأسقف المعلقة):
• الشاسيهات المعدنية: استخدام أوميجا وسي (C & Omega) من صاج معتمد ومجلفن سمك 0.5 مم إلى 0.6 مم وتثبيتها بفيشر تيش حديدي كل 60-70 سم كحد أقصى.
• ألواح الجبس: ألواح بيضاء عادية للصالات والغرف، وألواح خضراء مقاومة للرطوبة (Moisture Resistant) للحمامات والمطابخ والفراندات.
• معالجة الفواصل: شريط شبك فايبر ومعجون فواصل جبس ممتاز (Knauf Uniflott) لمنع ظهور أي شروخ طولية بعد الدهان.

٢. تأسيس النقاشة والدهانات:
• وش سيلر مائي (Water-based Sealer Primer) لتقوية سطح المحارة وتثبيته.
• سحب من 3 إلى 4 سكينات معجون داخلي ناعم بجودة عالية مع تغيير لون كل سكين للتأكد من تغطية السطح بالكامل.
• الصنفرة بماكينة الإضاءة الكاشفة الليد (Led Sanding Guide) لكشف أي تموجات أو عيوب واستعدالها بالكامل.

٣. التشطيب النهائي:
• وش بطانة مخفف بلون مقارب لدرجة اللون النهائي.
• وشين دهان نهائي قابل للغسيل (Semi-Gloss أو Eggshell مطفي حريري) من ماركات معتمدة مثل جوتن (Jotun Fenomastic) أو سيبس (Scib).`;
  }

  // 6. الألوميتال والأبواب والنجارة
  if (
    q.includes('ألوميتال') || 
    q.includes('شباك') || 
    q.includes('أبواب') || 
    q.includes('باب') || 
    q.includes('نجار') || 
    q.includes('زجاج') || 
    q.includes('حلوق') || 
    q.includes('window') || 
    q.includes('door')
  ) {
    return `${projectIntro}عزل الصوت والأتربة والحرارة يعتمد بنسبة 80% على قطاعات الألوميتال والأبواب المحكمة:

١. شبابيك وواجهات الألوميتال:
• اختيار قطاعات محملة وعريضة مثل قطاع (جامبو Jumbo) أو (PS كبير) أو (Falcon) مع عوازل كوتشوك EPDM وفرش دبل لمنع تسريب الأتربة ومياه الأمطار.
• الزجاج: دبل جلاس (Double Glazed) بمساحة فراغ هوائي بين اللوحين 10-12 مم مفرغة من الهواء لعزل الضوضاء الخارجية وصوت الشارع والحرارة بكفاءة ممتازة.
• فتحات تصريف مياه المطر (Mizrab): التأكد من وجود ثقوب صرف مياه الأمطار في مجرى السكة السفلي للنافذة.

٢. أبواب الغرف والباب الرئيسي:
• تركيب حلوق زفارة خشب موسكي محمل تثبت بكانات حديدية وفوم بوليمر عازل قبل المحارة.
• الباب الرئيسي: باب مصفح تركي أو إيطالي أصلي به كوالين أمان متعددة النقاط (مثل كالي أو تشيزا) مع حشو صوف صخري لعزل الصوت ومقاومة الحريق.
• أبواب الغرف: كبس قشرة خشب أرو أو HPL مقاوم للرطوبة والخدش ومفصلات ستانلس ستيل عريضة محملة.`;
  }

  // 7. توفير الميزانية وإدارة التكاليف
  if (
    q.includes('وفر') || 
    q.includes('توفير') || 
    q.includes('ميزاني') || 
    q.includes('رخيص') || 
    q.includes('أسعار') || 
    q.includes('تكلف') || 
    q.includes('budget') || 
    q.includes('cost')
  ) {
    return `${projectIntro}إليك الاستراتيجية الهندسية الذكية لضغط تكاليف التشطيب وتوفير ما يصل إلى 20-30% من الميزانية بدون أي تضحية بالجودة أو المتانة:

١. أين تنفق ولا تبخل أبداً (الدفين - التأسيس):
• السباكة (مواسير التغذية والصرف)، كابلات الكهرباء واللوحات، العزل المائي، تأسيس المحارة. هذه البنود ستعيش معك 30 سنة وأي توفير فيها سيكلفك أضعافاً لاحقاً في التكسير والإصلاح.

٢. أين توفر بذكاء شديد (الديكورات والفرش):
• البدائل الحديثة: استخدام بديل الخشب (WPC) وبديل الرخام (PVC Sheets) في جدار التلفزيون ومداخل الشقة؛ يعطيك نفس المظهر الفخم بربع تكلفة الرخام الطبيعي وخشب الأرو!
• البورسلين: استخدام بورسلين فرز أول في الريسبشن والطرقات والمساحات المكشوفة، بينما يمكنك استخدام سيراميك فرز أول أو فرز ثانٍ ممتاز في أرضيات الغرف المغلقة التي ستغطى بالسجاد والموبيليا.
• الأسقف: تجنب الزخارف الجبسية المعقدة واعتمد البساطة (Simple Flat Gypsum with Shadow Gap أو بيت نور ليد مستقيم)؛ هذا يوفر في أمتار الجبس ومصنعية الدهانات.

٣. نظام التعاقد مع المقاولين:
• تجنب التعاقد الشامل بدون مقايسة تفصيلية. اطلب دوماً مقايسة كميات ومواصفات دقيقة (BOQ)، واربط دفعات المقاول باستلام المهندس الاستشاري لكل مرحلة بنجاح.`;
  }

  // 8. مرحلة التسليم النهائي والتشطيبات
  if (
    q.includes('تسليم') || 
    q.includes('نظاف') || 
    q.includes('فرش') || 
    q.includes('مرحل') || 
    q.includes('stage')
  ) {
    return `${projectIntro}مراحل تشطيب الشقة مرتبة هندسياًตาม تسلسل الأعمال السليم (12 مرحلة):
1. التكسير والتعديلات المعمارية
2. تأسيس الكهرباء (تكسير وتركيب العلب والخراطيم)
3. تأسيس السباكة ومسارات التغذية والصرف
4. عزل أرضيات الحمامات والمطابخ واختبار الغمر 48 ساعة
5. المحارة (طرطشة مسمارية، بؤج وأوتار، ملء ودرع بالقدة)
6. جبسوم بورد والأسقف المعلقة وبيوت النور
7. تأسيس الدهانات وسحب معجون المحارة
8. توريد وتركيب أرضيات البورسلين والسيراميك
9. شبابيك الألوميتال وحلوق وأبواب الغرف
10. تشطيب الدهانات النهائية والألوان والديكور
11. تشطيب الكهرباء (اللقم والوشوش والسبوتات) والأطقم الصحية
12. النظافة الشاملة، تلميع الأرضيات، والفرش والتسليم النهائي.

يمكنك الضغط على أي مرحلة داخل خريطة التشطيب لمتابعة تفاصيلها والتحقق من بنود الفحص المعتمدة!`;
  }

  // Default Comprehensive Engineering Advisor Consultation
  return `${projectIntro}أهلاً بك! بصفتي المستشار الهندسي المعتمد لتشطيب شقتك:

سؤالك مهم جداً في أعمال التشطيب. لضمان أعلى جودة تنفيذية بأقل تكلفة:

١. الجودة الهندسية أولاً:
احرص دائماً على الالتزام بالمواصفات القياسية المصرية؛ كل خطوة يتم تنفيذها بشكل صحيح تحميك من تكاليف التكسير والإعادة.

٢. الفحص والاستلام:
لا تسلّم المقاول أو الفني دفعته المالية إلا بعد استلام البند بالقدة، ميزان المياه، أو اختبار الضغط المعتمد (سواء كبس السباكة أو غمر العزل المائي أو قياس أحمال الكهرباء).

٣. اختيار الخامات المعتمدة:
استثمر دائماً في الخامات المدفونة المعتمدة (كابلات السويدي، مواسير بولي بروبلين أصلية، عزل مائي كيميائي ممتاز، مونة محارة خشنة نظيفة).

هل لديك استفسار محدد عن بند معين (مثل المحارة، السباكة، العزل، السيراميك، الكهرباء، الجبسوم بورد، أو إدارة الميزانية)؟ يسعدني تقديم الخطوات الفنية الدقيقة لك فوراً!`;
}
